// catalog_js.mjs · writes docs/js/catalog.js from docs/js/catalog.json so score.js can import the
// catalog as an ES module anywhere (browser, Node, vendored copies) with no fetch and no JSON import.
//   node tools/catalog_js.mjs          write
//   node tools/catalog_js.mjs --check  exit 1 if catalog.js is out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const js = join(dirname(fileURLToPath(import.meta.url)), "..", "docs", "js");
const data = JSON.parse(readFileSync(join(js, "catalog.json"), "utf8"));
const out = "// catalog.js · GENERATED by tools/catalog_js.mjs from catalog.json. Do not edit by hand.\n"
  + "export const CATALOG = " + JSON.stringify(data) + ";\nexport default CATALOG;\n";
const path = join(js, "catalog.js");
if (process.argv.includes("--check")) {
  const ok = existsSync(path) && readFileSync(path, "utf8") === out;
  console.log(ok ? "catalog.js up to date" : "catalog.js OUT OF DATE");
  process.exit(ok ? 0 : 1);
}
writeFileSync(path, out);
console.log("wrote", path, out.length, "bytes");
